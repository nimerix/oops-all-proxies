// ---------- lettering
// Cinzel Black is bundled under the SIL OFL. Text is outlined so the header,
// logos and card backs match without a font download.
const fontBytes = await readFile(new URL("Cinzel-Black.ttf", import.meta.url));
const font = opentype.parse(fontBytes.buffer.slice(fontBytes.byteOffset, fontBytes.byteOffset + fontBytes.byteLength));
// opentype's own serialiser can emit NaN for rounded values.
const pathData = (path, digits) =>
  path.commands.map((c) =>
    c.type === "Z" ? "Z"
      : c.type === "Q" ? `Q${r(c.x1, digits)} ${r(c.y1, digits)} ${r(c.x, digits)} ${r(c.y, digits)}`
        : c.type === "C" ? `C${r(c.x1, digits)} ${r(c.y1, digits)} ${r(c.x2, digits)} ${r(c.y2, digits)} ${r(c.x, digits)} ${r(c.y, digits)}`
          : `${c.type}${r(c.x, digits)} ${r(c.y, digits)}`).join("");
// The fixed Latin name uses no ligatures or contextual substitutions.
const layout = (text, size, tracking) => {
  const run = [...text].map((letter) => font.charToGlyph(letter));
  let pen = 0;
  return run.map((glyph, i) => {
    const x = pen, width = glyph.advanceWidth * size / font.unitsPerEm;
    pen += (glyph.advanceWidth + (run[i + 1] ? font.getKerningValue(glyph, run[i + 1]) : 0)) * size / font.unitsPerEm + tracking;
    return { glyph, x, width, end: pen - tracking };
  });
};
const arcText = (text, size, cx, cy, radius, tracking) => {
  const run = layout(text, size, tracking), total = run.at(-1).end;
  return run.map(({ glyph, x, width }) => {
    const d = pathData(glyph.getPath(-width / 2, 0, size), 3);
    const turn = (x + width / 2 - total / 2) / radius * 180 / Math.PI;
    return d && `<path transform="translate(${cx} ${cy}) rotate(${r(turn)}) translate(0 ${-radius})" d="${d}"/>`;
  }).filter(Boolean).join("");
};

