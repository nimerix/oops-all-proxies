// PNG pHYs holds pixels per metre, so print tools read the 63 × 88 mm size
// instead of assuming their default DPI.
const withPrintDensity = (bytes) => {
  const chunk = Buffer.alloc(21);
  chunk.writeUInt32BE(9, 0);
  chunk.write("pHYs", 4, "ascii");
  chunk.writeUInt32BE(PX_PER_MM * 1000, 8);
  chunk.writeUInt32BE(PX_PER_MM * 1000, 12);
  chunk[16] = 1;
  let crc = 0xffffffff;
  for (const byte of chunk.subarray(4, 17)) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  chunk.writeUInt32BE((crc ^ 0xffffffff) >>> 0, 17);
  // The fixed-size IHDR ends at byte 33; pHYs precedes all image data.
  return Buffer.concat([bytes.subarray(0, 33), chunk, bytes.subarray(33)]);
};
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const printable = (scheme, source) => {
  const { pixels, width, height } = png(source, W * PX_PER_MM);
  const edge = rgb(scheme.back.edge), margin = 5 * PX_PER_MM;
  let nonOpaque = 0, edgeMismatches = 0, lopsided = 0;
  for (let i = 0; i < pixels.length; i += 4) {
    const x = (i / 4) % width, y = Math.floor(i / 4 / width);
    const inMargin = x < margin || y < margin || x >= width - margin || y >= height - margin;
    if (pixels[i + 3] !== 255) nonOpaque++;
    for (let c = 0; c < 3; c++) {
      if (Math.abs(pixels[i + c] - pixels[pixels.length - 4 - i + c]) > 48) lopsided++;
      if (inMargin && pixels[i + c] !== edge[c]) edgeMismatches++;
    }
  }
  const report = { scheme: scheme.id, width, height, nonOpaque, edgeMismatches, lopsided: r(lopsided / pixels.length, 5) };
  // Antialiasing and grain differ slightly between a shape and its half-turn;
  // anything one-way, such as upright text, is far above this limit.
  if (width * H !== height * W || nonOpaque || edgeMismatches || lopsided / pixels.length > 0.002) throw new Error(JSON.stringify(report));
  // Copy the top half onto its rotated partner so the print file is identical upside down.
  for (let i = 0; i < pixels.length / 2; i += 4) pixels.copy(pixels, pixels.length - 4 - i, i, i + 4);
  console.log(JSON.stringify(report));
  return withPrintDensity(PNG.sync.write({ width, height, data: pixels }, { colorType: 2, deflateLevel: 9 }));
};

// ---------- icons
// ICO with PNG-encoded entries; no platform-specific tooling needed.
const ico = (icons) => {
  const header = Buffer.alloc(6 + 16 * icons.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(icons.length, 4);
  let offset = header.length;
  icons.forEach(({ size, bytes }, i) => {
    const entry = 6 + i * 16;
    header[entry] = header[entry + 1] = size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(bytes.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += bytes.length;
  });
  return Buffer.concat([header, ...icons.map(({ bytes }) => bytes)]);
};
