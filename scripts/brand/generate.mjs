// ---------- symbol: a hand of cards with one slipping loose
const fan = (spec, lift = 20, cw = 22, ch = 30.8) => {
  const turned = (deg) => [Math.cos(deg * Math.PI / 180), Math.sin(deg * Math.PI / 180)];
  const cards = spec.map(({ turn, push = 0, tip = 0, side = 0 }) => {
    const [c, s] = turned(turn), d = lift + push;
    return { cx: d * s + side * c, cy: -d * c + side * s, angle: turn + tip };
  });
  const corners = cards.flatMap(({ cx, cy, angle }) => {
    const [c, s] = turned(angle);
    return [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([a, b]) => [cx + a * cw / 2 * c - b * ch / 2 * s, cy + a * cw / 2 * s + b * ch / 2 * c]);
  });
  const xs = corners.map((p) => p[0]), ys = corners.map((p) => p[1]);
  return { cards, cw, ch, x: Math.min(...xs), y: Math.min(...ys), w: Math.max(...xs) - Math.min(...xs), h: Math.max(...ys) - Math.min(...ys) };
};
const hand = fan([{ turn: -18 }, { turn: 6 }, { turn: 52, push: -2, tip: 18, side: 4 }]);
// Three cards blur together at 16 and 32 px, so small icons show two.
const smallHand = fan([{ turn: -12 }, { turn: 50, push: -3, tip: 16, side: 6 }]);
// Fits a fan into a 64 unit square with `pad` units of margin.
const fanParts = ({ cards, cw, ch, x, y, w, h }, pad) => {
  const k = (64 - 2 * pad) / Math.max(w, h);
  return {
    group: `translate(${r((64 - w * k) / 2 - x * k)} ${r((64 - h * k) / 2 - y * k)}) scale(${r(k)})`,
    rects: cards.map(({ cx, cy, angle }) => `x="${-cw / 2}" y="${-ch / 2}" width="${cw}" height="${ch}" rx="3" transform="translate(${r(cx)} ${r(cy)}) rotate(${angle})"`),
  };
};
// Cards are separated by an outline in the colour of the surface behind them.
const fanSvg = (geometry, fills, surface, pad, gap) => {
  const { group, rects } = fanParts(geometry, pad);
  return `<g transform="${group}">${rects.map((attrs, i) => `<rect ${attrs} fill="${fills[i]}" stroke="${surface}" stroke-width="${gap}"/>`).join("")}</g>`;
};
